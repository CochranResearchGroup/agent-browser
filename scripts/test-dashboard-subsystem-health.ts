import assert from "node:assert/strict";
import { currentHealth, overallHealth, runtimeHealthRow, nativeHealthRow } from "../packages/dashboard/src/lib/subsystem-health.ts";
const now = 100_000;
assert.equal(nativeHealthRow([{ slot: 1, state: "unavailable" }], now).state, "failed");
assert.equal(nativeHealthRow([{ slot: 1, state: "ready" }, { slot: 8, state: "unavailable" }], now).state, "attention");
assert.equal(nativeHealthRow([{ slot: 1, state: "ready" }], now).state, "healthy");
for (const invalid of [[], {}, null, [{ slot: 1 }]]) assert.equal(nativeHealthRow(invalid, now).state, "unknown");
assert.equal(runtimeHealthRow({ ready: true, state: "ready" }, now).state, "unknown", "a ready flag without dated evidence is not health");
assert.equal(runtimeHealthRow({ ready: true, state: "ready", observedAtEpochMs: now - 30_000 }, now).state, "unknown");
assert.equal(runtimeHealthRow({ ready: true, state: "ready", observedAtEpochMs: now + 10_000 }, now).state, "unknown");
const degraded = runtimeHealthRow({ ready: false, state: "degraded", observedAtEpochMs: now, issues: [{ code: "native_verification_missing" }, { code: "https://private.invalid/path" }] }, now);
assert.match(degraded.detail, /native_verification_missing/);
assert.doesNotMatch(degraded.detail, /private.invalid/);
const ready = runtimeHealthRow({ ready: true, state: "ready", observedAtEpochMs: now }, now);
assert.equal(ready.state, "healthy");
assert.equal(currentHealth(ready, now + 30_000).state, "unknown");
assert.equal(overallHealth([ready, { ...ready, state: "unknown" }]), "unknown");
assert.equal(overallHealth([ready, { ...ready, state: "attention" }]), "attention");
assert.equal(overallHealth([ready, { ...ready, state: "failed" }]), "failed");
assert.equal(overallHealth([]), "unknown");
console.log("Subsystem health evidence checks passed");
