#!/usr/bin/env node
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const source=new URL('../docs/dev/contracts/public-error-recovery-client-dashboard.v1.json',import.meta.url);
const target=new URL('../packages/client/src/client-recovery.generated.js',import.meta.url);
const bytes=readFileSync(source),registry=JSON.parse(bytes);
const codes=Object.fromEntries(Object.entries(registry.codes).sort(([a],[b])=>(a<b?-1:a>b?1:0)).map(([code,entry])=>{
 if(!/^[a-z][a-z0-9_]{0,127}$/.test(code)||!registry.recipes[entry.recipe])throw Error(`Unqualified client recovery code: ${code}`);
 return [code,{recipe:entry.recipe,evidenceClass:entry.evidenceClass}];
}));
// Operative recipe data only. Source inventories and per-check audit records are
// build-time qualification, not material for the runtime/browser bundle.
const interfaces=Object.fromEntries(Object.entries(registry.interfaces??{}).map(([name,value])=>[name,{kind:value.kind,...(value.uri?{uri:value.uri}:{})}]));
const digest=createHash('sha256').update(bytes).digest('hex');
const output=`// Generated by scripts/generate-client-recovery.js. Do not edit.\nexport const CLIENT_RECOVERY_SOURCE_SHA256 = ${JSON.stringify(digest)};\nexport const CLIENT_RECOVERY_CODES = ${JSON.stringify(codes,null,2)};\nexport const CLIENT_RECOVERY_RECIPES = ${JSON.stringify(registry.recipes,null,2)};\nexport const CLIENT_RECOVERY_INTERFACES = ${JSON.stringify(interfaces,null,2)};\n`;
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==output){process.stderr.write(`Client recovery artifact is stale. Run node scripts/generate-client-recovery.js (${fileURLToPath(target)}).\n`);process.exitCode=1;}
}else writeFileSync(target,output);
